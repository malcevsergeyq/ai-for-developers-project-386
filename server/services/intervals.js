/**
 * Арифметика времени внутри суток. Вынесена отдельно, потому что одна и та же проверка
 * пересечения нужна в трёх местах контракта: правила расписания не должны накладываться,
 * свободные слоты генерируются с оглядкой на активные брони, создание брони проверяет
 * тот же конфликт. Две независимые реализации разъехались бы на первой правке длительности.
 */

/** `HH:MM`, 00:00..23:59. Секунд в контракте нет — время в API всегда до минут. */
export const TIME_PATTERN = /^([01]\d|2[0-3]):([0-5]\d)$/;

export const isTimeString = (value) => typeof value === 'string' && TIME_PATTERN.test(value);

export const toMinutes = (time) => {
  const [hours, minutes] = time.split(':');
  return Number(hours) * 60 + Number(minutes);
};

/**
 * Полуинтервалы `[start, end)`: стык впритык (13:00–18:00 после 09:00–13:00) пересечением
 * не считается, иначе соседние слоты объявляли бы друг друга занятыми.
 */
export const overlaps = (aStart, aEnd, bStart, bEnd) => aStart < bEnd && bStart < aEnd;
